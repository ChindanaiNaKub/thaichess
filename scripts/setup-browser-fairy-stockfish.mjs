import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const require = createRequire(import.meta.url);
const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packageJsonPath = require.resolve('fairy-stockfish-nnue.wasm/package.json', {
  paths: [path.join(repoRoot, 'client')],
});
const packageDir = path.dirname(packageJsonPath);
const packageJson = JSON.parse(await readFile(packageJsonPath, 'utf8'));
const outputDir = path.join(repoRoot, 'client', 'public', 'engines');

await mkdir(outputDir, { recursive: true });

await Promise.all([
  copyFile(path.join(packageDir, 'stockfish.js'), path.join(outputDir, 'stockfish.js')),
  copyFile(path.join(packageDir, 'stockfish.wasm'), path.join(outputDir, 'stockfish.wasm')),
]);

const pthreadWorkerSource = await readFile(path.join(packageDir, 'stockfish.worker.js'), 'utf8');
await writeFile(
  path.join(outputDir, 'stockfish.worker.js'),
  pthreadWorkerSource.replace(
    'if(typeof e.data.urlOrBlob==="string"){importScripts(e.data.urlOrBlob)}else{var objectUrl=URL.createObjectURL(e.data.urlOrBlob);importScripts(objectUrl);URL.revokeObjectURL(objectUrl)}',
    'if(typeof e.data.urlOrBlob==="string"){importScripts(e.data.urlOrBlob)}else if(e.data.urlOrBlob instanceof Blob){var objectUrl=URL.createObjectURL(e.data.urlOrBlob);importScripts(objectUrl);URL.revokeObjectURL(objectUrl)}else{importScripts("/engines/stockfish.js")}',
  ),
);

await writeFile(path.join(outputDir, 'fairy-stockfish.js'), `/* Generated by scripts/setup-browser-fairy-stockfish.mjs.
 * Source: fairy-stockfish-nnue.wasm@${packageJson.version}
 * License: GPL-3.0
 */
let engine = null;
let failed = false;
const pendingCommands = [];

function sendError(error) {
  const message = error instanceof Error ? error.message : String(error);
  self.postMessage('error ' + message);
}

function sendCommand(command) {
  if (failed) return;
  if (engine) {
    engine.postMessage(command);
    return;
  }
  pendingCommands.push(command);
}

self.onmessage = (event) => {
  sendCommand(String(event.data));
};

importScripts('/engines/stockfish.js');

const assetVersion = '${packageJson.version}';

Stockfish({
  mainScriptUrlOrBlob: '/engines/stockfish.js?v=' + assetVersion,
  locateFile: (file) => '/engines/' + file + '?v=' + assetVersion,
})
  .then((instance) => {
    engine = instance;
    engine.addMessageListener((line) => self.postMessage(String(line)));
    for (const command of pendingCommands.splice(0)) {
      engine.postMessage(command);
    }
  })
  .catch((error) => {
    failed = true;
    sendError(error);
  });
`);

await writeFile(path.join(outputDir, 'manifest.json'), `${JSON.stringify({
  generatedBy: 'scripts/setup-browser-fairy-stockfish.mjs',
  package: packageJson.name,
  version: packageJson.version,
  license: packageJson.license,
  homepage: packageJson.homepage,
}, null, 2)}
`);
